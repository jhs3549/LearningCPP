// 참조자(Reference) 매개변수 예제
#include <iostream>

using namespace std;

void modify(int &x, int &y) // 참조자는 컴파일된 후에는 실제 변수의 메모리 주소로 대체되는, 심볼테이블에서만 사용되는 개념입니다.
{ 
    x += 10; // x에 10을 더합니다.
    y += 20; // y에 20을 더합니다.
    cout << "x의 주소값: " << &x << ", y의 주소값: " << &y << endl; // x와 y의 주소값을 출력합니다.
}

int main() 
{
    int a = 5; // 변수 a를 5로 초기화합니다.
    int b = 15; // 변수 b를 15로 초기화합니다.

    cout << "a의 주소값: " << &a << ", b의 주소값: " << &b << endl; // a와 b의 주소값을 출력합니다.
    cout << "Before modify: a = " << a << ", b = " << b << endl;

    modify(a, b); // a와 b의 값을 참조로 전달하여 modify 함수를 호출합니다. 실제로 호출 시 전달되는 값은 a와 b의 메모리 주소입니다. x와 y에 실제로 들어가는 값은 a와 b의 주소입니다. 
        // 따라서 함수 내부에서 x와 y를 변경하면 a와 b의 값이 직접 변경됩니다. 심볼테이블 상으로 x와 a는 같은 메모리 주소를 가리키게 되고, y와 b도 같은 메모리 주소를 가리키게 됩니다.
        // 컴파일된 어셈블리 코드를 보면, 함수 호출 시 a와 b의 주소가 스택에 푸시되고, 함수 내부에서는 이 주소를 사용하여 직접 a와 b의 값을 변경하는 것을 확인할 수 있습니다.
        // 즉, 참조에 사용된 변수는 컴파일되면 사라지고, 함수 내부에서는 원래 변수의 메모리 주소를 사용하여 값을 변경하게 됩니다.

    cout << "After modify: a = " << a << ", b = " << b << endl;

    return 0;
}